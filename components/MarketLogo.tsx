const sizeClasses: Record<LogoSize, string> = {
  sm: "h-8 w-8 rounded-lg",
  md: "h-10 w-10 rounded-lg",
  lg: "h-12 w-12 rounded-xl",
  xl: "h-14 w-14 rounded-xl md:h-16 md:w-16",
};

const imagePaddingClasses: Record<LogoSize, string> = {
  sm: "p-1",
  md: "p-1.5",
  lg: "p-1.5",
  xl: "p-2",
};

function LogoMark({
  src,
  label,
  size,
}: {
  src?: string;
  label: string;
  size: LogoSize;
}) {
  const initials = label.replace(/[^A-Z0-9]/gi, "").slice(0, 3).toUpperCase();

  return (
    <span
      className={`inline-flex shrink-0 items-center justify-center overflow-hidden border border-slate-200 bg-white shadow-sm ${sizeClasses[size]}`}
      aria-hidden="true"
    >
      {src ? (
        <img
          src={src}
          alt=""
          width={64}
          height={64}
          loading={size === "xl" ? "eager" : "lazy"}
          decoding="async"
          className={`h-full w-full object-contain ${imagePaddingClasses[size]}`}
        />
      ) : (
        <span className="flex h-full w-full items-center justify-center bg-slate-900 px-1 text-center text-[10px] font-extrabold leading-none text-cyan-300 md:text-xs">
          {initials || "FON"}
        </span>
      )}
    </span>
  );
}

export function FundLogo({
  fundCode,
  managerSlug,
  size = "lg",
}: {
  fundCode: string;
  managerSlug?: string;
  size?: LogoSize;
}) {
  const normalizedCode = fundCode.toUpperCase();
  const resolvedManager = managerSlug ?? fundManagersByCode[normalizedCode];

  return (
    <LogoMark
      src={resolvedManager ? fundManagerLogos[resolvedManager] : undefined}
      label={normalizedCode}
      size={size}
    />
  );
}

export function InstrumentLogo({
  symbol,
  size = "sm",
}: {
  symbol: string;
  size?: LogoSize;
}) {
  const normalizedSymbol = symbol.toUpperCase();
  const managerSlug = fundManagersByCode[normalizedSymbol];
  const src = stockLogos[normalizedSymbol] ??
    (managerSlug ? fundManagerLogos[managerSlug] : undefined);

  return <LogoMark src={src} label={normalizedSymbol} size={size} />;
}
